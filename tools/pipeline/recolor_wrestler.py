"""씨름꾼 스프라이트를 프로젝트 도깨비 팔레트로 옮긴다.

PixelLab 생성물이 회청색 무채 일변도라 잡도깨비(따뜻한 흙빛 + 탁한 자주)와 나란히
두면 혼자 색이 빠져 보인다는 지적을 받았다. 명도 구조는 그대로 두고 색만 바꾼다.

기준 팔레트는 assets/sprites/enemies/dokkaebi_idle_e.png 에서 뽑았다.
  피부  탁한 자주 계열 (150,125,143) / (66,35,67)
  옷    따뜻한 흙빛과 올리브 (156,121,78) / (135,141,114) / (98,97,90)
  샅바  적자주 (90,51,61) 계열. 씨름꾼 정체성이라 유지한다
"""

import sys
from PIL import Image

# 원본색 -> 목표색. 같은 색은 어디에 있든 같은 재질이라 전역 대응으로 충분하다
MAP = {
    # 피부 (얼굴, 가슴, 팔). 밝은 쪽부터
    (189, 178, 178): (182, 150, 166),
    (158, 145, 151): (150, 125, 143),
    (145, 145, 146): (139, 132, 104),   # 바지. 명도는 피부와 겹치나 재질이 다르다
    (142, 130, 137): (132, 106, 126),
    (133, 122, 130): (112, 86, 110),
    # 옷 (저고리, 머리). 밝은 쪽부터
    (99, 98, 108): (88, 78, 64),
    (87, 85, 100): (76, 68, 58),
    (78, 76, 93): (66, 60, 54),
    (70, 69, 86): (58, 52, 48),
    (57, 54, 70): (46, 42, 40),
    (49, 45, 58): (38, 35, 34),
    (40, 37, 50): (32, 29, 28),
    (27, 26, 36): (24, 22, 22),
    (19, 17, 28): (18, 16, 16),
    (11, 10, 16): (12, 11, 11),
    # 샅바. 적자주 쪽으로 한 단계 눅인다
    (178, 65, 82): (170, 66, 70),
    (170, 47, 74): (158, 56, 62),
    (166, 52, 66): (154, 58, 60),
    (162, 43, 94): (150, 54, 74),
    (162, 57, 105): (148, 62, 82),
    (159, 40, 68): (148, 52, 58),
    (148, 56, 79): (138, 60, 64),
    (126, 36, 70): (118, 46, 56),
    (122, 50, 78): (114, 52, 58),
    (104, 38, 67): (98, 44, 50),
    (100, 18, 37): (94, 30, 36),
    (93, 32, 62): (88, 40, 46),
    (68, 18, 39): (66, 26, 32),
    (59, 23, 30): (58, 28, 30),
    (40, 7, 14): (40, 14, 16),
    (25, 0, 6): (26, 8, 10),
}

KEEP = {(0, 0, 0), (0, 1, 5)}


def nearest(col):
    """대응표에 없는 색은 가장 가까운 원본색의 대응을 쓴다."""
    best, best_d = None, None
    for src in MAP:
        d = sum((a - b) ** 2 for a, b in zip(src, col))
        if best_d is None or d < best_d:
            best, best_d = src, d
    return MAP[best]


def convert(path):
    img = Image.open(path).convert("RGBA")
    px = img.load()
    unmapped = set()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            if a == 0 or (r, g, b) in KEEP:
                continue
            if (r, g, b) in MAP:
                px[x, y] = MAP[(r, g, b)] + (a,)
            else:
                unmapped.add((r, g, b))
                px[x, y] = nearest((r, g, b)) + (a,)
    img.save(path)
    return len(unmapped)


def main():
    for path in sys.argv[1:]:
        n = convert(path)
        print(path.split("/")[-1], "근사 처리한 색", n)


if __name__ == "__main__":
    main()
